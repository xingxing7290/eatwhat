const assert = require('node:assert/strict')
const http = require('node:http')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')

async function main () {
  const html = fs.readFileSync(path.join(__dirname, '../../server/public/guest-order.html'))
  const server = http.createServer((req, res) => { res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); res.end(html) })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  try {
    const meals = Array.from({ length: 51 }, (_, i) => ({ _id: i.toString(16).padStart(24, '0'), name: `测试菜${String(i).padStart(2, '0')}`, category: '家常菜' }))
    const session = { title: '人数上限测试', status: 'open', canOrder: true, supportsIdempotentCreate: true }
    let writes = 0
    const route = async route => {
      const request = route.request(); const url = new URL(request.url())
      if (request.method() === 'GET' && url.pathname.endsWith('/orders/old-access')) return route.fulfill({ json: { order: { revision: 1, guestName: '老访客', note: '保留整单备注', items: meals.map(meal => ({ mealId: meal._id, name: meal.name, quantity: 1, note: meal === meals[1] ? '保留单菜备注' : '' })) } } })
      if (request.method() === 'GET') return route.fulfill({ json: url.searchParams.has('statusOnly') ? { session } : { session, meals } })
      writes++
      const body = request.postDataJSON(); assert.equal(body.items.length, 50)
      return route.fulfill({ status: 201, json: { accessToken: 'test-access', order: { revision: 1, guestName: body.guestName, note: body.note, items: body.items } } })
    }
    const page = await browser.newPage({ viewport: { width: 320, height: 844 } }); page.setDefaultTimeout(12000)
    await page.route('**/guest-orders/public/**', route)
    await page.goto(`http://127.0.0.1:${server.address().port}/guest-order/limit-new`)
    await page.locator('.meal').first().getByRole('button', { name: '＋ 想吃' }).waitFor()
    await page.evaluate(() => { for (let i = 0; i < 50; i++) document.querySelectorAll('.meal')[i].querySelector('.add').click() })
    await page.getByText('已达 50 道上限', { exact: false }).first().waitFor()
    const last = page.locator('.meal').nth(50).getByRole('button', { name: '已达 50 道上限' })
    assert.equal(await last.isDisabled(), true)
    assert.match(await page.locator('#cartHint').innerText(), /已达 50 道上限/)
    await page.locator('.meal').nth(0).getByRole('button', { name: '增加测试菜00' }).click()
    assert.match(await page.locator('#cartHint').innerText(), /合计 51 份/)
    await page.locator('.meal').nth(0).getByRole('button', { name: '减少测试菜00' }).click()
    await page.locator('.meal').nth(0).getByRole('button', { name: '减少测试菜00' }).click()
    await page.locator('.meal').nth(50).getByRole('button', { name: '＋ 想吃' }).click()
    await page.getByRole('button', { name: '查看菜单' }).click()
    await page.locator('#guestName').fill('访客')
    await page.getByRole('button', { name: '提交给主人' }).click()
    await page.getByText('上次的点菜单已提交给主人', { exact: false }).waitFor()
    assert.equal(writes, 1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.close()
    const old = await browser.newPage({ viewport: { width: 320, height: 844 } }); old.setDefaultTimeout(12000)
    await old.addInitScript(() => localStorage.setItem('eatwhat.guestOrder.limit-old', 'old-access'))
    await old.route('**/guest-orders/public/**', route)
    await old.goto(`http://127.0.0.1:${server.address().port}/guest-order/limit-old`)
    await old.getByRole('button', { name: '查看 / 修改' }).click()
    await old.getByText('点菜单超过 50 道菜', { exact: false }).waitFor()
    assert.equal(await old.getByRole('button', { name: '保存修改' }).isDisabled(), true)
    assert.equal(await old.locator('#orderNote').inputValue(), '保留整单备注')
    assert.equal(await old.getByRole('textbox', { name: '测试菜01的备注' }).inputValue(), '保留单菜备注')
    await old.getByRole('dialog', { name: '我的点菜单' }).getByRole('button', { name: '减少测试菜00' }).click()
    assert.equal(await old.getByRole('button', { name: '保存修改' }).isEnabled(), true)
    assert.equal(await old.locator('#orderNote').inputValue(), '保留整单备注')
    assert.equal(writes, 1, 'a legacy over-limit order must not submit without review')
    await old.close()
    console.log('Guest order limits passed: 50 dishes, portion changes, safe submission and oversized legacy recovery')
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
