    releasePage = undefined; mode = 'page-hold'
    await page.getByRole('button', { name: '返回', exact: true }).click()
    await search.waitFor(); await search.focus()
    for (let i = 0; i < 100 && !releasePage; i++) await new Promise(resolve => setTimeout(resolve, 20))
    assert.equal(typeof releasePage, 'function')
    mode = 'normal'; releasePage()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(await search.evaluate(node => document.activeElement === node), true, 'returning data must not steal focus from a new action')
    await page.getByRole('button', { name: '查看家常菜09' }).first().click()
    await page.getByRole('heading', { name: '家常菜09' }).waitFor()
