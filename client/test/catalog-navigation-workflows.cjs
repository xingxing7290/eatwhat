const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = process.env.EATWHAT_TEST_URL || 'http://127.0.0.1:5179'
if (!/^http:\/\/127\.0\.0\.1:(5178|5179)$/.test(base)) throw new Error('Catalog checks require a local server')
async function main () {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } }); page.setDefaultTimeout(12000)
    await page.addInitScript(() => { localStorage.setItem('token', 'test'); localStorage.setItem('user', JSON.stringify({ id: 'u1', householdId: 'h1' })) })
    const meals = Array.from({ length: 20 }, (_, index) => ({ _id: `m${index + 1}`, name: `家常菜${String(index + 1).padStart(2, '0')}`, category: '家常菜', subcategory: '热菜', description: '', tags: index < 2 ? ['清淡'] : [], ingredients: [], steps: [], photos: [], favorite: index < 2, supportsConditionalEdit: true, editVersion: { revision: 'v1', updatedAt: '2026-10-28T08:00:00.000Z' } }))
    const errors = []; const requests = []; let mode = 'normal'; page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/**', async route => {
      const req = route.request(); const url = new URL(req.url()); const path = url.pathname.replace(/^\/api/, '')
      if (path === '/auth/household-scope') return route.fulfill({ json: { supportsHouseholdScope: true, householdId: 'h1' } })
      if (path === '/meals/categories') return route.fulfill({ json: [{ category: '家常菜', subcategory: '热菜' }] })
      if (path === '/meals/tags' || path === '/wishlist' || path === '/memories') return route.fulfill({ json: [] })
      if (path === '/meals') {
        if (mode === 'legacy') return route.fulfill({ json: meals })
        if (mode === 'missing') return route.fulfill({ json: { data: null, total: 0 } })
        if (mode === 'duplicate') return route.fulfill({ json: { data: [meals[0], meals[0]], total: 2, page: 1, limit: 8 } })
        if (mode === 'wrong-page') return route.fulfill({ json: { data: meals.slice(0, 8), total: 20, page: 2, limit: 8 } })
        const search = url.searchParams.get('search') || ''; requests.push(url.searchParams.toString())
        if (search === '慢查询') await new Promise(resolve => setTimeout(resolve, 700))
        const rows = meals.filter(meal => meal.name.includes(search) && (!url.searchParams.get('category') || meal.category === url.searchParams.get('category')))
        const current = Number(url.searchParams.get('page') || 1); const limit = Number(url.searchParams.get('limit') || 8)
        return route.fulfill({ json: { data: rows.slice((current - 1) * limit, current * limit), total: rows.length, page: current, limit } }).catch(() => {})
      }
      if (path.startsWith('/meals/')) return route.fulfill({ json: meals.find(meal => path === `/meals/${meal._id}`) || {} })
      return route.fulfill({ json: {} })
    })
    await page.goto(`${base}/meals`)
    const search = page.getByRole('textbox', { name: '搜索菜品' })
    await page.getByRole('complementary', { name: '菜品分类' }).getByRole('button', { name: '家常菜' }).click()
    await search.fill('家常菜')
    await page.getByText('筛选结果 · 20 道').waitFor()
    await page.getByLabel('菜品分页').getByRole('button', { name: '下一页' }).click()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    await page.waitForFunction(() => { const q = new URL(location.href).searchParams; return q.get('q') === '家常菜' && q.get('category') === '家常菜' && q.get('page') === '2' })
    await page.reload()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(await search.inputValue(), '家常菜')
    assert.equal(await page.getByRole('complementary', { name: '菜品分类' }).getByRole('button', { name: '家常菜' }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: '查看家常菜09' }).first().click()
    await page.getByRole('heading', { name: '家常菜09' }).waitFor()
    await page.getByRole('button', { name: '返回', exact: true }).click()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(new URL(page.url()).searchParams.get('page'), '2')
    await page.getByRole('button', { name: '编辑家常菜09' }).first().click()
    await page.getByRole('heading', { name: '编辑菜品' }).waitFor()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(new URL(page.url()).searchParams.get('category'), '家常菜')
    await page.getByRole('button', { name: '编辑家常菜09' }).first().click()
    await page.getByRole('heading', { name: '编辑菜品' }).waitFor()
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(new URL(page.url()).searchParams.get('page'), '2', 'saving an edit returns to the filtered page')
    await search.fill('慢查询'); await page.waitForTimeout(250); await search.fill('家常菜01')
    await page.getByRole('button', { name: '查看家常菜01' }).first().waitFor(); await page.waitForTimeout(800)
    assert.equal(await search.inputValue(), '家常菜01')
    await page.waitForFunction(() => new URL(location.href).searchParams.get('q') === '家常菜01')
    await page.goto(`${base}/meals?page=99&q=${encodeURIComponent('家常菜')}`)
    await page.getByRole('button', { name: '查看家常菜17' }).first().waitFor()
    await page.waitForFunction(() => new URL(location.href).searchParams.get('page') === '3')
    await page.goto(`${base}/meals?category=${encodeURIComponent('家常菜')}&subcategory=${encodeURIComponent('热菜')}&page=2&view=list`)
    await page.locator('.meals-list').getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    await page.evaluate(() => { void document.querySelector('#app').__vue_app__.config.globalProperties.$router.push({ name: 'meals', query: { q: '家常菜01' } }) })
    await page.getByRole('button', { name: '查看家常菜01' }).first().waitFor()
    await page.goBack()
    await page.locator('.meals-list').getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    assert.equal(new URL(page.url()).searchParams.get('subcategory'), '热菜')
    await page.goto(`${base}/meals?page=0&favorite=bad&subcategory=orphan&view=bad`)
    await page.getByRole('button', { name: '查看家常菜01' }).first().waitFor()
    assert.equal(await search.inputValue(), '')
    assert.ok(requests.some(value => new URLSearchParams(value).get('page') === '1'))
    mode = 'legacy'; await page.goto(`${base}/meals`)
    await page.getByRole('button', { name: '查看家常菜01' }).first().waitFor()
    assert.equal(await page.locator('.meals-grid .meal-card-wrapper').count(), 8, 'legacy complete arrays must be paginated locally')
    await page.getByLabel('菜品分页').getByRole('button', { name: '下一页' }).click()
    await page.getByRole('button', { name: '查看家常菜09' }).first().waitFor()
    await search.fill('家常菜20')
    await page.getByText('筛选结果 · 1 道').waitFor()
    await page.getByRole('button', { name: '查看家常菜20' }).first().waitFor()
    await search.fill('')
    await page.getByRole('complementary', { name: '菜品分类' }).getByRole('button', { name: '我的收藏' }).click()
    await page.getByText('筛选结果 · 2 道').waitFor()
    assert.equal(await page.locator('.meals-grid .meal-card-wrapper').count(), 2, 'legacy favorite filtering must use the complete list')
    for (const failure of ['missing', 'duplicate', 'wrong-page']) {
      mode = failure; await page.goto(`${base}/meals`)
      await page.getByText('无法加载菜品', { exact: false }).waitFor()
      assert.equal(await page.locator('.meal-card-wrapper').count(), 0, `${failure} response must not be displayed as a valid catalog`)
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('Catalog navigation checks passed: filters, pagination, detail and editor returns, invalid links and stale searches')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
