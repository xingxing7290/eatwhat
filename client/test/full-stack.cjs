const assert = require('node:assert/strict')
const { chromium } = require('playwright')

const base = process.env.EATWHAT_E2E_URL
if (base !== 'http://127.0.0.1:5189') throw new Error('Refusing to run outside the dedicated loopback tunnel')

async function main () {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    const marker = await context.request.get(`${base}/api/health`)
    assert.equal(marker.status(), 200)
    assert.equal(marker.headers()['x-eatwhat-isolated'], 'codex-e2e-only')
    assert.equal(await marker.text(), 'healthy')

    const guestPage = await context.request.get(`${base}/guest-order/e2e-only-guest-token`)
    assert.equal(guestPage.status(), 200)
    assert.match(guestPage.headers()['content-type'], /text\/html/)
    assert.match(guestPage.headers()['cache-control'], /no-store/)
    assert.equal(guestPage.headers()['referrer-policy'], 'no-referrer')
    assert.match(await guestPage.text(), /我的点菜单/)
    const guestApi = await context.request.get(`${base}/guest-orders/public/e2e-only-guest-token`)
    assert.equal(guestApi.status(), 200)
    assert.match(guestApi.headers()['cache-control'], /no-store/)
    const guestData = await guestApi.json()
    assert.equal(guestData.session.title, '隔离联调宴请')

    async function login (username) {
      await page.goto(`${base}/login`)
      await page.getByPlaceholder('请输入用户名').fill(username)
      await page.getByPlaceholder('请输入密码').fill('e2e-only-password')
      await page.getByPlaceholder('请输入密码').press('Enter')
      await page.waitForURL('**/dashboard')
      await page.getByRole('heading', { name: /好好吃饭/ }).waitFor()
    }
    async function apiGet (path) {
      return page.evaluate(async endpoint => {
        const response = await fetch(`/api${endpoint}`, { headers: { Authorization: `Bearer ${localStorage.getItem('token')}` } })
        if (!response.ok) throw new Error(`GET ${endpoint}: ${response.status}`)
        return response.json()
      }, path)
    }
    await login('e2e-user-a')
    const me = await apiGet('/auth/me')
    assert.equal(me.household.name, 'E2E 家庭甲')
    console.log('E2E: login and household loaded')

    await page.goto(`${base}/settings`)
    await page.getByPlaceholder('给你们的小家取个名字').fill('尚未保存的家庭名')
    await page.getByPlaceholder('请输入昵称').fill('联调昵称')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByText('保存成功').waitFor()
    assert.equal(await page.getByPlaceholder('给你们的小家取个名字').inputValue(), '尚未保存的家庭名')
    await page.locator('input[type=file]').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64') })
    await page.getByRole('button', { name: '上传头像' }).click()
    await page.getByText('头像已更新').waitFor()
    const avatar = page.locator('.avatar-preview img')
    await avatar.waitFor()
    await page.waitForFunction(() => document.querySelector('.avatar-preview img')?.complete)
    assert.ok(await avatar.evaluate(image => image.naturalWidth > 0), 'uploaded avatar must actually load in the browser')
    const memberAvatar = page.locator('.member-avatar img').first()
    await page.waitForFunction(() => document.querySelector('.member-avatar img')?.complete)
    assert.ok(await memberAvatar.evaluate(image => image.naturalWidth > 0), 'member avatar must actually load in the browser')
    assert.equal(await page.getByPlaceholder('给你们的小家取个名字').inputValue(), '尚未保存的家庭名')
    const updatedProfile = await apiGet('/auth/me')
    assert.equal(updatedProfile.user.displayName, '联调昵称')
    assert.equal(updatedProfile.household.members[0].displayName, '联调昵称')
    assert.ok(updatedProfile.household.members[0].avatarUrl.includes('/uploads/'))
    assert.equal(new URL(updatedProfile.user.avatarUrl).origin, base, 'server must retain the public port in new avatar URLs')
    await page.getByRole('button', { name: '刷新', exact: true }).first().click()
    await page.getByRole('button', { name: '放弃并刷新' }).click()
    await page.waitForFunction(() => { const image = document.querySelector('.avatar-preview img'); return image?.complete && image.naturalWidth > 0 })
    await page.waitForFunction(() => { const image = document.querySelector('.member-avatar img'); return image?.complete && image.naturalWidth > 0 })
    console.log('E2E: profile and avatar saved without discarding household draft')

    await page.goto(`${base}/meals`)
    await Promise.all([
      page.waitForResponse(response => new URL(response.url()).pathname === '/api/meals' && new URL(response.url()).searchParams.get('search') === '联调菜谱 01' && response.status() === 200),
      page.getByPlaceholder('搜索菜名、描述、食材或做法...').fill('联调菜谱 01')
    ])
    await page.locator('.meals-grid .meal-card-wrapper').filter({ hasText: '联调菜谱 01' }).first().click()
    await page.getByRole('heading', { name: '联调菜谱 01' }).waitFor()
    await page.getByRole('button', { name: '记录做过' }).click()
    const memoryDialog = page.getByRole('dialog', { name: '记录饭后回忆' })
    await memoryDialog.waitFor()
    await memoryDialog.locator('textarea').fill('真实联调回忆')
    await memoryDialog.locator('input[type=file]').setInputFiles({ name: 'e2e.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64') })
    await memoryDialog.getByRole('button', { name: '保存' }).click()
    await page.getByText('真实联调回忆').waitFor()
    await page.goto(`${base}/photo-album`)
    await page.locator('.photo-card').first().click()
    await page.getByRole('dialog', { name: '饭桌回忆' }).waitFor()
    console.log('E2E: memory photo and album loaded')

    await page.goto(`${base}/meals/editor`)
    await page.getByPlaceholder('给这道菜起个名字').fill('联调新菜')
    await page.locator('.cover-box').locator('..').locator('input[type=file]').setInputFiles({ name: 'meal.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64') })
    await page.getByPlaceholder('食材', { exact: true }).fill('联调鸡蛋')
    await page.getByPlaceholder('用量').fill('2个')
    await page.getByRole('button', { name: '添加食材' }).click()
    await page.getByPlaceholder('写下一个步骤').fill('先搅拌再炒')
    await page.getByRole('button', { name: '添加步骤' }).click()
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await page.waitForURL('**/meals')
    const created = await apiGet('/meals?search=%E8%81%94%E8%B0%83%E6%96%B0%E8%8F%9C&page=1&limit=8')
    assert.equal(created.data.length, 1)
    assert.equal(created.data[0].ingredients[0].name, '联调鸡蛋')
    assert.equal(new URL(created.data[0].imageUrl).origin, base, 'server must retain the public port in new recipe image URLs')
    const today = await page.evaluate(() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` })
    await page.goto(`${base}/selection?date=${today}&mealType=dinner&suggestedMealId=${created.data[0]._id}`)
    await page.locator('.selection-info').getByText('联调新菜').waitFor()
    await page.getByRole('button', { name: '保存安排' }).click()
    await page.waitForURL('**/calendar')
    await page.waitForFunction(() => { const images = [...document.querySelectorAll('.added-by-avatar img')]; return images.length > 0 && images.every(image => image.complete && image.naturalWidth > 0) })
    const day = await apiGet(`/schedules/day/${today}`)
    assert.equal(day.meals.dinner.some(item => item.meal?.name === '联调新菜'), true)
    console.log('E2E: recipe created and scheduled')

    await page.goto(`${base}/weekly-plan`)
    await page.getByRole('button', { name: '生成草稿' }).click()
    await page.getByText('规则生成草稿').waitFor()
    await page.getByRole('button', { name: '应用到日历' }).click()
    await page.getByRole('button', { name: '确认替换' }).click()
    await page.getByText('已应用到日历').waitFor()
    const week = await apiGet(`/weekly-plans?weekStart=${today}`)
    assert.equal(week.days.length, 7)
    assert.equal(week.days.every(item => item.scheduleExists), true)
    console.log('E2E: weekly plan applied')

    await page.goto(`${base}/shopping-list`)
    await page.getByRole('button', { name: '从排餐生成' }).click()
    await page.getByText('联调食材', { exact: true }).waitFor()
    await page.getByText('联调食材', { exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.item-row.checked') !== null)
    console.log('E2E: shopping list updated')

    await page.goto(`${base}/wishlist`)
    await page.getByRole('button', { name: '添加想吃' }).click()
    await page.getByPlaceholder('比如：冬阴功火锅、楼下那家牛肉面').fill('联调想吃')
    await page.getByRole('dialog', { name: '添加想吃' }).getByRole('button', { name: '保存' }).click()
    await page.getByText('联调想吃').waitFor()

    await page.evaluate(() => { localStorage.removeItem('token'); localStorage.removeItem('user') })
    await login('e2e-user-b')
    const meB = await apiGet('/auth/me')
    assert.notEqual(meB.household.inviteCode, me.household.inviteCode)
    const mealsB = await apiGet('/meals')
    assert.equal(mealsB.length, 1)
    assert.equal(mealsB[0].name, '乙家庭专属菜')
    assert.equal((await apiGet('/wishlist')).length, 0)
    await page.evaluate(() => { localStorage.removeItem('token'); localStorage.removeItem('user') })
    await page.goto(`${base}/apply-account#invite=${encodeURIComponent(me.household.inviteCode)}`)
    await page.getByPlaceholder('请输入家人的邀请码').waitFor()
    assert.equal(await page.getByPlaceholder('请输入家人的邀请码').inputValue(), me.household.inviteCode)
    await page.getByPlaceholder('请输入用户名').fill('e2e-user-c')
    await page.getByPlaceholder('请输入密码', { exact: true }).fill('e2e-only-password')
    await page.getByPlaceholder('请再次输入密码').fill('e2e-only-password')
    await page.getByRole('button', { name: '创建账号' }).click()
    await page.waitForURL('**/login?username=e2e-user-c')
    await login('e2e-user-c')
    const meC = await apiGet('/auth/me')
    assert.equal(meC.household.id, me.household.id)
    const mealsC = await apiGet('/meals')
    assert.equal(mealsC.some(meal => meal.name === '联调新菜'), true)
    assert.equal(mealsC.some(meal => meal.name === '乙家庭专属菜'), false)
    await page.goto(`${base}/apply-account#invite=${encodeURIComponent(meB.household.inviteCode)}`)
    await page.getByRole('button', { name: '使用当前账号加入' }).click()
    await page.waitForURL('**/settings')
    assert.equal(await page.getByPlaceholder('输入伴侣的邀请码').inputValue(), meB.household.inviteCode)
    assert.equal((await apiGet('/auth/me')).household.id, me.household.id, 'opening an invitation must not switch households automatically')
    await page.getByRole('button', { name: '加入', exact: true }).click()
    await page.getByRole('button', { name: '取消' }).last().click()
    assert.equal((await apiGet('/auth/me')).household.id, me.household.id, 'cancelling must not switch households')
    await page.getByRole('button', { name: '加入', exact: true }).click()
    await page.getByRole('button', { name: '确认加入' }).click()
    await page.getByText('已加入小家').waitFor()
    assert.equal((await apiGet('/auth/me')).household.id, meB.household.id)
    assert.equal((await apiGet('/meals'))[0].name, '乙家庭专属菜')
    await page.evaluate(() => { localStorage.removeItem('token'); localStorage.removeItem('user') })
    await page.goto(`${base}/apply-account#invite=${encodeURIComponent(meB.household.inviteCode)}`)
    await page.getByPlaceholder('请输入家人的邀请码').waitFor()
    await page.getByPlaceholder('请输入用户名').fill('e2e-user-d')
    await page.getByPlaceholder('请输入密码', { exact: true }).fill('e2e-only-password')
    await page.getByPlaceholder('请再次输入密码').fill('e2e-only-password')
    await page.getByRole('button', { name: '创建账号' }).click()
    await page.waitForURL('**/login?username=e2e-user-d')
    await login('e2e-user-d')
    const meD = await apiGet('/auth/me')
    assert.equal(meD.household.id, meB.household.id)
    const mealsD = await apiGet('/meals')
    assert.equal(mealsD.length, 1)
    assert.equal(mealsD[0].name, '乙家庭专属菜')
    console.log('E2E: distinct invitation links join only their intended households')
    assert.deepEqual(errors, [])
    console.log('Full-stack E2E passed: login, recipe, memory photo, album, calendar, week plan, shopping, wishlist and household isolation')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
