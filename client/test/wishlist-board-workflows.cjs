const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = process.env.EATWHAT_TEST_URL || 'http://127.0.0.1:5179'
if (!/^http:\/\/127\.0\.0\.1:(5178|5179)$/.test(base)) throw new Error('Wishlist checks require a local server')

async function main () {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    page.setDefaultTimeout(12000)
    await page.addInitScript(() => { localStorage.setItem('token', 'test-token'); localStorage.setItem('user', JSON.stringify({ id: 'u1', householdId: 'h1' })) })
    const rows = Array.from({ length: 29 }, (_, i) => ({ _id: `w${String(i).padStart(2, '0')}`, title: `心愿${String(i).padStart(2, '0')}`, note: '', category: '家常', status: i < 20 ? 'open' : i < 26 ? 'planned' : i < 28 ? 'done' : 'legacy', priority: 'normal', votes: [], supportsSafeMealLink: true, supportsMealLinkVisibility: true, mealLinkStatus: 'unlinked', createdAt: new Date(1700000000000 - i * 1000).toISOString() }))
    rows[12].mealId = { _id: 'm1', name: '家常菜' }
    const errors = []; const requests = []; let releaseSlow; let releasePage; let holdPage = false; let failPage = false; let detailError = false; let preflight = 'ok'; let createRequests = 0
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/**', async route => {
      const request = route.request(); const url = new URL(request.url()); const path = url.pathname.replace(/^\/api/, '')
      if (path === '/auth/household-scope') return route.fulfill({ json: { supportsHouseholdScope: true, householdId: 'h1' } })
      if (path === '/meals/m1') return route.fulfill({ json: { _id: 'm1', name: '家常菜' } })
      if (path === '/meals' && request.method() === 'GET') return route.fulfill({ json: { data: [], page: 1, limit: 8, total: 0 } })
      if (path === '/meals/categories' || path === '/meals/tags') return route.fulfill({ json: [] })
      if (path.startsWith('/schedules/day/')) return route.fulfill({ json: { date: path.split('/').pop(), scheduleExists: false, scheduleVersion: null, meals: { breakfast: [], lunch: [], dinner: [] } } })
      if (path === '/meals' && request.method() === 'POST') { createRequests++; return route.fulfill({ status: 503, json: { error: '模拟创建响应丢失' } }) }
      if (path.startsWith('/wishlist/') && request.method() === 'GET') {
        if (detailError || preflight === 'error') return route.fulfill({ status: 503, json: { error: '模拟记录暂时不可读' } })
        const row = rows.find(row => row._id === path.split('/').pop())
        if (preflight === 'changed' && row) row.mealLinkStatus = 'unavailable'
        return route.fulfill({ json: row || {} })
      }
      if (path === '/wishlist' && request.method() === 'GET') {
        const query = Object.fromEntries(url.searchParams); requests.push(query)
        if (query.search === '心愿01') await new Promise(resolve => { releaseSlow = resolve })
        if (holdPage && query.page === '2') await new Promise(resolve => { releasePage = resolve })
        if (failPage && query.page === '2') return route.fulfill({ status: 503, json: { error: '分页读取失败' } })
        const bucket = row => ['open', 'planned', 'done'].includes(row.status) ? row.status : 'unknown'
        const totals = { open: 0, planned: 0, done: 0, unknown: 0 }; const matched = { ...totals }
        rows.forEach(row => totals[bucket(row)]++)
        const filtered = rows.filter(row => (query.status === 'all' || bucket(row) === query.status) && (query.priority === 'all' || row.priority === query.priority) && (!query.search || [row.title, row.note, row.category].some(value => value.includes(query.search))))
        filtered.forEach(row => matched[bucket(row)]++)
        const number = Number(query.page); const limit = Number(query.limit)
        return route.fulfill({ json: { supportsWishlistBoard: true, page: number, limit, search: query.search, status: query.status, priority: query.priority, matched, totals, total: filtered.length, items: filtered.slice((number - 1) * limit, number * limit) } })
      }
      return route.fulfill({ json: {} })
    })
    await page.goto(`${base}/wishlist`)
    await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    assert.equal(await page.locator('.wish-card').count(), 12)
    assert.equal(requests[0].view, 'board')
    await page.getByRole('textbox', { name: '搜索想吃记录' }).fill('心愿')
    await page.getByRole('group', { name: '按状态筛选' }).getByRole('button', { name: '想吃', exact: true }).click()
    await page.getByLabel('按优先级筛选').selectOption('normal')
    await page.getByText('共 20 条匹配记录 · 第 1 / 2 页').waitFor()
    await page.getByRole('button', { name: '下一页' }).focus()
    await page.keyboard.press('Enter')
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    await page.waitForFunction(() => document.activeElement?.closest('.board-pagination') && document.activeElement.textContent.trim() === '第 2 / 2 页')
    assert.equal(await page.getByRole('button', { name: '下一页' }).isDisabled(), true)
    await page.getByRole('button', { name: '上一页' }).focus()
    await page.keyboard.press('Enter')
    await page.getByText('共 20 条匹配记录 · 第 1 / 2 页').waitFor()
    await page.waitForFunction(() => document.activeElement?.closest('.board-pagination') && document.activeElement.textContent.trim() === '第 1 / 2 页')
    holdPage = true
    await page.getByRole('button', { name: '下一页' }).focus()
    await page.keyboard.press('Enter')
    await page.waitForFunction(() => document.querySelector('.board')?.getAttribute('aria-busy') === 'true')
    await page.getByRole('textbox', { name: '搜索想吃记录' }).focus()
    for (let i = 0; i < 100 && !releasePage; i++) await new Promise(resolve => setTimeout(resolve, 20))
    assert.equal(typeof releasePage, 'function')
    holdPage = false; releasePage()
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    assert.equal(await page.getByRole('textbox', { name: '搜索想吃记录' }).evaluate(input => document.activeElement === input), true, 'a late page response must not steal focus')
    await page.getByRole('button', { name: '上一页' }).click()
    await page.getByText('共 20 条匹配记录 · 第 1 / 2 页').waitFor()
    failPage = true
    await page.getByRole('button', { name: '下一页' }).focus()
    await page.keyboard.press('Enter')
    await page.getByText('想吃清单暂时无法加载：分页读取失败').waitFor()
    await page.waitForFunction(() => document.activeElement?.classList.contains('list-error-focus') && document.activeElement.textContent.includes('分页读取失败'))
    failPage = false
    await page.getByRole('button', { name: '重新加载' }).click()
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    rows[12].title = '心愿12（已更新）'
    await page.getByRole('button', { name: '刷新当前结果' }).click()
    await page.getByText('心愿12（已更新）', { exact: true }).waitFor()
    assert.equal(await page.getByRole('textbox', { name: '搜索想吃记录' }).inputValue(), '心愿')
    assert.equal(await page.getByLabel('按优先级筛选').inputValue(), 'normal')
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    assert.equal(createRequests, 0, 'refresh must not create records or recipes')
    rows[12].title = '心愿12'
    await page.getByRole('button', { name: '刷新当前结果' }).click()
    await page.getByText('心愿12', { exact: true }).waitFor()
    await page.locator('.wish-card').filter({ hasText: '心愿12' }).getByRole('button', { name: '选择日期安排' }).click()
    const schedule = page.getByRole('dialog', { name: '安排想吃的菜' })
    await schedule.getByLabel('日期').fill('2026-12-31')
    await schedule.getByRole('button', { name: '下一步：核对安排' }).click()
    await page.getByRole('button', { name: '移除家常菜' }).waitFor()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('dialog', { name: '放弃未保存的内容？' }).getByRole('button', { name: '放弃并离开' }).click()
    await page.waitForURL('**/wishlist')
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    assert.equal(await page.getByRole('textbox', { name: '搜索想吃记录' }).inputValue(), '心愿')
    assert.equal(await page.getByLabel('按优先级筛选').inputValue(), 'normal')
    assert.equal(await page.getByRole('group', { name: '按状态筛选' }).getByRole('button', { name: '想吃', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.locator('.wish-card').filter({ hasText: '心愿12' }).getByRole('button', { name: '安排今天晚餐' }).click()
    await page.waitForURL('**/selection?*fromWishlist=1')
    await page.getByRole('button', { name: '移除家常菜' }).waitFor()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('dialog', { name: '放弃未保存的内容？' }).getByRole('button', { name: '放弃并离开' }).click()
    await page.getByText('共 20 条匹配记录 · 第 2 / 2 页').waitFor()
    await page.getByRole('button', { name: '清除筛选' }).click()
    await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    assert.equal(await page.getByRole('textbox', { name: '搜索想吃记录' }).evaluate(input => document.activeElement === input), true)
    await page.reload()
    await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    await page.evaluate(() => history.replaceState({ ...history.state, eatwhatWishlistView: { search: '其他家庭的搜索', status: 'open', priority: 'normal', page: 2, userId: 'other', householdId: 'other-home' } }, ''))
    await page.reload()
    await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    assert.equal(await page.getByRole('textbox', { name: '搜索想吃记录' }).inputValue(), '', 'view state from another household must not be restored')
    preflight = 'changed'
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByRole('button', { name: '转菜品' }).click()
    await page.getByText('想吃记录或菜谱关联已变化', { exact: false }).waitFor()
    assert.equal(createRequests, 0, 'a changed association must never create a recipe')
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByText('原关联菜谱不可用', { exact: false }).waitFor()
    rows[0].mealLinkStatus = 'unlinked'; preflight = 'ok'
    await page.reload(); await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    preflight = 'error'
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByRole('button', { name: '转菜品' }).click()
    await page.getByText('无法核对最新想吃记录，本次没有创建菜谱', { exact: false }).waitFor()
    assert.equal(createRequests, 0, 'a failed preflight must not create or flag an uncertain write')
    assert.equal(await page.getByText('创建结果不确定', { exact: false }).count(), 0)
    preflight = 'ok'
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByRole('button', { name: '转菜品' }).click()
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByText('创建结果不确定', { exact: false }).waitFor()
    await page.getByRole('button', { name: '下一页' }).click()
    await page.getByText('共 29 条匹配记录 · 第 2 / 3 页').waitFor()
    await page.getByText('有 1 条关联或创建结果待核对的记录不在当前结果中。').waitFor()
    detailError = true
    await page.getByRole('button', { name: '查看待核对记录' }).click()
    await page.getByText('想吃清单暂时无法加载', { exact: false }).waitFor()
    await page.getByRole('button', { name: '返回全部清单' }).click()
    await page.getByRole('button', { name: '查看待核对记录' }).waitFor()
    detailError = false
    await page.getByRole('button', { name: '查看待核对记录' }).click()
    await page.locator('.wish-card').filter({ hasText: '心愿00' }).getByText('创建结果不确定', { exact: false }).waitFor()
    await page.getByRole('button', { name: '返回全部清单' }).click()
    await page.getByText('共 29 条匹配记录 · 第 2 / 3 页').waitFor()
    const search = page.getByRole('textbox', { name: '搜索想吃记录' })
    await search.fill('心愿01')
    await page.waitForFunction(() => document.querySelector('.filter-heading p')?.textContent.includes('正在更新'))
    await page.waitForRequest(request => request.url().includes('search=%E5%BF%83%E6%84%BF01'))
    await search.fill('心愿02')
    await page.getByText('共 1 条匹配记录 · 第 1 / 1 页').waitFor()
    await page.getByText('心愿02', { exact: true }).waitFor()
    releaseSlow()
    await page.waitForTimeout(300)
    assert.equal(await page.getByText('心愿01', { exact: true }).count(), 0, 'stale response must not replace newer search')
    await search.fill('')
    await page.getByText('共 29 条匹配记录 · 第 1 / 3 页').waitFor()
    await page.getByRole('group', { name: '按状态筛选' }).getByRole('button', { name: '待核对' }).click()
    await page.getByText('共 1 条匹配记录 · 第 1 / 1 页').waitFor()
    const unknown = page.locator('.wish-card').filter({ hasText: '心愿28' })
    await unknown.getByText('记录状态无法识别', { exact: false }).waitFor()
    assert.equal(await unknown.getByRole('button').count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('Wishlist board checks passed: pagination, stale searches and hidden pending recovery')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
