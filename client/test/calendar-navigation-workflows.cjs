const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = process.env.EATWHAT_TEST_URL || 'http://127.0.0.1:5179'
if (!/^http:\/\/127\.0\.0\.1:(5178|5179)$/.test(base)) throw new Error('Calendar navigation tests require a local server')
async function main () {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } }); page.setDefaultTimeout(12000)
    await page.clock.setFixedTime(new Date(2026, 9, 28, 12))
    await page.addInitScript(() => { localStorage.setItem('token', 'test'); localStorage.setItem('user', JSON.stringify({ id: 'u1', householdId: 'h1' })) })
    const errors = []; const reads = []; page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/**', route => {
      const url = new URL(route.request().url()); const path = url.pathname.replace(/^\/api/, '')
      if (path === '/auth/household-scope') return route.fulfill({ json: { supportsHouseholdScope: true, householdId: 'h1' } })
      if (path === '/schedules') { reads.push(`${url.searchParams.get('year')}-${url.searchParams.get('month')}`); return route.fulfill({ json: [] }) }
      if (path.startsWith('/schedules/day/')) return route.fulfill({ json: { date: path.split('/').pop(), scheduleExists: false, scheduleVersion: null, meals: { breakfast: [], lunch: [], dinner: [] } } })
      if (path === '/meals') return route.fulfill({ json: { data: [], total: 0, page: 1, limit: 8 } })
      if (path === '/wishlist' || path === '/meals/categories' || path === '/meals/tags') return route.fulfill({ json: [] })
      return route.fulfill({ json: {} })
    })
    await page.goto(`${base}/calendar?date=2026-12-31`)
    await page.getByText('已定位到 2026-12-31', { exact: false }).waitFor()
    await page.locator('.mobile-date-card.target-date').waitFor()
    await page.locator('.mobile-month-nav').getByRole('button', { name: '下个月' }).click()
    await page.waitForURL('**/calendar?month=2027-01')
    await page.locator('.mobile-month-nav').getByText('2027年01月').waitFor()
    await page.reload(); await page.locator('.mobile-month-nav').getByText('2027年01月').waitFor()
    await page.locator('.mobile-date-list').getByRole('button', { name: '安排2027-01-10早餐' }).click()
    await page.waitForURL('**/selection?date=2027-01-10&mealType=breakfast')
    await page.getByRole('button', { name: '保存安排' }).waitFor()
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await page.waitForURL('**/calendar?date=2027-01-10')
    await page.getByText('已定位到 2027-01-10', { exact: false }).waitFor()
    await page.reload(); await page.locator('.mobile-date-card.target-date').waitFor()
    await page.locator('.mobile-month-nav').getByRole('button', { name: '下个月' }).click()
    await page.waitForURL('**/calendar?month=2027-02')
    await page.locator('.mobile-month-nav').getByText('2027年02月').waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.mobile-month-nav button')].some(button => button.getAttribute('aria-label') === '下个月' && !button.disabled))
    await page.evaluate(() => { void document.querySelector('#app').__vue_app__.config.globalProperties.$router.push({ name: 'calendar', query: { date: '2027-04-15' } }) })
    await page.waitForURL('**/calendar?date=2027-04-15')
    await page.getByText('已定位到 2027-04-15', { exact: false }).waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.mobile-month-nav button')].some(button => button.getAttribute('aria-label') === '下个月' && !button.disabled))
    await page.goBack(); await page.locator('.mobile-month-nav').getByText('2027年02月').waitFor()
    await page.evaluate(() => { void document.querySelector('#app').__vue_app__.config.globalProperties.$router.push({ name: 'calendar', query: { month: '2027-13' } }) })
    await page.getByText('日历链接中的日期无效').waitFor()
    assert.equal(new URL(page.url()).searchParams.get('month'), '2027-02')
    assert.ok(reads.includes('2027-4'))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    console.log('Calendar navigation checks passed: retained month, dated selection, history and invalid links')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
