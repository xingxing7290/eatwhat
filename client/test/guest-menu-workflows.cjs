const assert = require('node:assert/strict')
const http = require('node:http')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')

async function main () {
  const html = fs.readFileSync(path.join(__dirname, '../../server/public/guest-order.html'))
  const server = http.createServer((req, res) => { res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); res.end(html) })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || undefined })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    page.setDefaultTimeout(10000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const meals = Array.from({ length: 650 }, (_, i) => ({ _id: i.toString(16).padStart(24, '0'), name: i === 649 ? '末页特色菜' : i === 648 ? '延迟旧结果' : `菜品${String(i).padStart(4, '0')}`, category: i < 325 ? '热菜' : '素菜' }))
    const longName = 'LongDishName'.repeat(8); meals[1].name = longName
    const session = { title: '测试菜单', householdName: '测试家庭', status: 'open', canOrder: true, supportsGuestMenuPagination: true }
    let slowStarted
    const slowRequest = new Promise(resolve => { slowStarted = resolve })
    let failedOnce = false; let holdPage = false; let pageFail = false; let releasePage
    await page.route('**/guest-orders/public/**', async route => {
      const url = new URL(route.request().url())
      if (url.searchParams.has('statusOnly')) return route.fulfill({ json: { session } })
      const query = (url.searchParams.get('search') || '').toLowerCase()
      const category = url.searchParams.get('category') || ''
      const number = Number(url.searchParams.get('page')); const limit = Number(url.searchParams.get('limit'))
      assert.equal(limit, 24)
      if (holdPage && number === 2 && !query && !category) await new Promise(resolve => { releasePage = resolve })
      if (pageFail && number === 3 && !query && !category) return route.fulfill({ status: 503, json: { error: '翻页断网' } })
      if (query === '延迟') { slowStarted(); await new Promise(resolve => setTimeout(resolve, 1200)) }
      if (query === '出错' && !failedOnce) { failedOnce = true; return route.fulfill({ status: 503, json: { error: '测试断网' } }) }
      if (query === '异常响应') return route.fulfill({ json: { session, meals: [], menu: { page: number, limit, total: 500, totalPages: 1, categories: [] } } })
      const searched = meals.filter(meal => [meal.name, meal.category].join(' ').toLowerCase().includes(query))
      const filtered = searched.filter(meal => !category || meal.category === category)
      const counts = new Map()
      searched.forEach(meal => counts.set(meal.category, (counts.get(meal.category) || 0) + 1))
      return route.fulfill({ json: { session, meals: filtered.slice((number - 1) * limit, number * limit), menu: { page: number, limit, total: filtered.length, totalPages: Math.max(1, Math.ceil(filtered.length / limit)), categories: [...counts].map(([name, count]) => ({ name, count })) } } })
    })
    await page.goto(`http://127.0.0.1:${server.address().port}/guest-order/menu-test`)
    await page.getByText('650 道菜', { exact: false }).waitFor()
    assert.equal(await page.locator('.meal').count(), 24)
    assert.equal(await page.getByText('第 1 / 28 页').count(), 2)
    await page.setViewportSize({ width: 320, height: 844 })
    const longCard = page.locator('.meal').filter({ hasText: longName })
    assert.equal(await longCard.locator('h3').evaluate(node => node.scrollWidth <= node.clientWidth), true, 'long menu names must remain readable')
    await longCard.getByRole('button', { name: '＋ 想吃' }).click()
    await page.getByRole('button', { name: '查看菜单' }).click()
    const longRow = page.locator('.cart-row').filter({ hasText: longName })
    assert.equal(await longRow.evaluate(node => node.scrollWidth <= node.clientWidth), true, 'long selected names must remain within the order sheet')
    const rowBox = await longRow.boundingBox()
    for (const button of await longRow.locator('.stepper button').all()) {
      const box = await button.boundingBox()
      assert.ok(box.width >= 44 && box.height >= 44 && box.x >= rowBox.x && box.x + box.width <= rowBox.x + rowBox.width, 'quantity controls must remain visible and tappable')
    }
    await longRow.getByRole('button', { name: `减少${longName}` }).click()
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    if (process.env.EATWHAT_GUEST_MENU_SHOT) await page.screenshot({ path: process.env.EATWHAT_GUEST_MENU_SHOT })
    const firstMeal = page.locator('.meal').filter({ hasText: '菜品0000' })
    const addFirst = firstMeal.getByRole('button', { name: '＋ 想吃' })
    const cartStatus = page.locator('.cart-copy')
    assert.equal(await cartStatus.getAttribute('role'), 'status')
    assert.equal(await cartStatus.getAttribute('aria-atomic'), 'true')
    assert.equal(await page.locator('.cart-icon').getAttribute('aria-hidden'), 'true')
    assert.equal(await addFirst.getAttribute('aria-describedby'), 'meal-name-000000000000000000000000')
    assert.ok((await addFirst.boundingBox()).height >= 44)
    await addFirst.focus()
    await page.keyboard.press('Enter')
    assert.match(await cartStatus.innerText(), /已选 1 道菜[\s\S]*合计 1 份 · 尚未提交/)
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '增加菜品0000', 'adding a dish keeps focus on its quantity controls')
    await page.keyboard.press('Enter')
    assert.match(await cartStatus.innerText(), /合计 2 份 · 尚未提交/)
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '增加菜品0000', 'incrementing retains focus')
    await firstMeal.getByRole('button', { name: '减少菜品0000' }).focus()
    await page.keyboard.press('Enter')
    await page.keyboard.press('Enter')
    assert.equal(await page.evaluate(() => document.activeElement.textContent), '＋ 想吃', 'removing the last portion returns focus to the add button')
    await page.keyboard.press('Enter')
    assert.equal(await page.locator('.meal').filter({ hasText: '菜品0000' }).getByRole('button', { name: '增加菜品0000' }).count(), 1)
    await page.setViewportSize({ width: 320, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'narrow menus must not overflow')
    const cardBox = await firstMeal.boundingBox()
    for (const button of await firstMeal.locator('.stepper button').all()) {
      const box = await button.boundingBox()
      assert.ok(box.width >= 44 && box.height >= 44, 'quantity controls must remain easy to tap on narrow screens')
      assert.ok(box.x >= cardBox.x && box.x + box.width <= cardBox.x + cardBox.width, 'quantity buttons must fit within the card')
    }
    const stepperBox = await firstMeal.locator('.stepper').boundingBox()
    assert.ok(stepperBox.x >= cardBox.x && stepperBox.x + stepperBox.width <= cardBox.x + cardBox.width, 'quantity controls must fit within the card')
    await page.setViewportSize({ width: 390, height: 844 })
    holdPage = true
    await page.getByRole('button', { name: '下一页（顶部）' }).click()
    for (let i = 0; i < 100 && !releasePage; i++) await new Promise(resolve => setTimeout(resolve, 20))
    assert.equal(typeof releasePage, 'function')
    await page.getByRole('textbox', { name: '搜索菜品' }).focus()
    const pageResponse = page.waitForResponse(response => new URL(response.url()).searchParams.get('page') === '2')
    releasePage(); await pageResponse
    await page.getByText('第 2 / 28 页').first().waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'search', 'late page results must not steal focus from search')
    holdPage = false
    await page.getByRole('button', { name: '上一页（顶部）' }).focus()
    await page.keyboard.press('Enter')
    await page.getByText('第 1 / 28 页').first().waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'menuNextTop', 'when previous becomes disabled, focus moves to the available page button')
    await page.keyboard.press('Enter')
    await page.getByText('第 2 / 28 页').first().waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'menuNextTop', 'pagination retains focus after loading')
    pageFail = true
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: '重新加载菜单' }).waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.textContent), '重新加载菜单', 'a failed page load moves focus to retry')
    pageFail = false
    await page.keyboard.press('Enter')
    await page.getByText('第 3 / 28 页').first().waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'menuHeading')
    await page.getByRole('button', { name: '上一页（顶部）' }).click()
    await page.getByText('第 2 / 28 页').first().waitFor()
    await page.locator('.meal').filter({ hasText: '菜品0024' }).getByRole('button', { name: '＋ 想吃' }).click()
    await page.getByRole('button', { name: '查看菜单' }).click()
    await page.locator('.cart-row').filter({ hasText: '菜品0000' }).waitFor()
    await page.locator('.cart-row').filter({ hasText: '菜品0024' }).waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'closeCart', 'opening the modal moves focus into it')
    await page.keyboard.press('Shift+Tab')
    assert.equal(await page.evaluate(() => document.activeElement.id), 'submitOrder', 'reverse tab wraps inside the modal')
    await page.keyboard.press('Tab')
    assert.equal(await page.evaluate(() => document.activeElement.id), 'closeCart', 'forward tab wraps inside the modal')
    const firstRow = page.locator('.cart-row').filter({ hasText: '菜品0000' })
    await firstRow.getByRole('button', { name: '增加菜品0000' }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), '增加菜品0000', 'quantity changes retain keyboard focus')
    await firstRow.getByRole('button', { name: '减少菜品0000' }).click()
    await page.evaluate(() => { window.__cartHintChanges = 0; window.__cartHintObserver = new MutationObserver(() => { window.__cartHintChanges++ }); window.__cartHintObserver.observe(document.querySelector('#cartHint'), { childList: true, characterData: true, subtree: true }) })
    await firstRow.getByRole('textbox', { name: '菜品0000的备注' }).fill('少辣')
    assert.equal(await page.evaluate(() => window.__cartHintChanges), 0, 'unchanged status should not be re-announced while typing')
    await page.evaluate(() => window.__cartHintObserver.disconnect())
    await page.keyboard.press('Escape')
    assert.equal(await page.evaluate(() => document.activeElement.id), 'openCart', 'closing returns focus to the opener')
    await page.getByRole('button', { name: '查看菜单' }).click()
    assert.equal(await firstRow.getByRole('textbox', { name: '菜品0000的备注' }).inputValue(), '少辣')
    await page.getByRole('button', { name: '继续选菜' }).click()
    const search = page.getByRole('textbox', { name: '搜索菜品' })
    await search.fill('末页')
    await page.getByText('末页特色菜', { exact: true }).waitFor()
    await page.getByText('1 道菜', { exact: false }).waitFor()
    assert.equal(await page.locator('#cartTitle').innerText(), '已选 2 道菜')
    await search.fill('延迟')
    await slowRequest
    await page.getByRole('button', { name: '全部 更新中', exact: true }).waitFor()
    await search.fill('末页')
    await page.getByText('末页特色菜', { exact: true }).waitFor()
    await page.waitForTimeout(1500)
    assert.equal(await page.getByText('延迟旧结果', { exact: true }).count(), 0, 'a stale response must not replace newer search results')
    await search.fill('')
    await page.getByText('650 道菜', { exact: false }).waitFor()
    await page.getByRole('button', { name: /^素菜 325$/ }).click()
    await page.getByText('325 道菜', { exact: false }).waitFor()
    assert.equal(await page.getByRole('button', { name: /^素菜 325$/ }).getAttribute('aria-pressed'), 'true')
    assert.equal(await page.evaluate(() => document.activeElement.dataset.category), '素菜', 'category focus survives asynchronous rendering')
    assert.equal(await page.locator('#cartTitle').innerText(), '已选 2 道菜')
    await page.getByRole('button', { name: /^全部 650$/ }).click()
    await search.fill('出错')
    await page.getByRole('button', { name: '重新加载菜单' }).waitFor()
    await page.getByRole('button', { name: '全部 未更新', exact: true }).waitFor()
    await page.getByRole('button', { name: '重新加载菜单' }).focus()
    await page.keyboard.press('Enter')
    await page.getByText('没有找到匹配的菜', { exact: false }).waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.id), 'menuHeading', 'a successful retry restores focus to the results heading')
    await search.fill('异常响应')
    await page.getByRole('button', { name: '重新加载菜单' }).waitFor()
    assert.equal(await page.locator('.meal').count(), 0, 'malformed results must not display stale meals')
    await search.fill('菜品0000')
    await page.locator('.meal').filter({ hasText: '菜品0000' }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.deepEqual(errors, [])
    await page.close()

    const legacy = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    await legacy.route('**/guest-orders/public/**', route => route.fulfill({ json: { session: { ...session, supportsGuestMenuPagination: undefined }, meals: meals.slice(0, 600) } }))
    await legacy.goto(`http://127.0.0.1:${server.address().port}/guest-order/legacy-test`)
    await legacy.getByText('当前服务器仅提供前 600 道菜', { exact: false }).waitFor()
    assert.equal(await legacy.locator('.meal').count(), 600)
    await legacy.getByRole('textbox', { name: '搜索菜品' }).fill('菜品0599')
    await legacy.getByText('菜品0599', { exact: true }).waitFor()
    await legacy.getByRole('button', { name: '全部 1', exact: true }).waitFor()
    await legacy.getByRole('button', { name: '素菜 1', exact: true }).waitFor()
    assert.equal(await legacy.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await legacy.close()
    console.log('Guest menu workflows passed: pagination, complete search, categories, stale responses, cart and legacy guard')
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
